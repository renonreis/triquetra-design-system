/**
 * Copies the Geist Sans variable font (SIL OFL 1.1, from @fontsource-variable/geist) into
 * src/styles/generated/ and writes its @font-face rules.
 *
 * Outputs (git-ignored, mirrored into dist/ by `build:css`):
 *   fonts.css             @font-face for family "Geist" (normal + italic, every subset, wght 100–900)
 *   fonts/*.woff2         the font files, referenced as ./fonts/<file>
 *   fonts/OFL.txt         the font license, which must ship with the files
 *
 * Subsets use `unicode-range`, so browsers only download the ones a page needs.
 */
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'src/styles/generated');
const FONTS = join(OUT, 'fonts');
const FAMILY = 'Geist';

const source = dirname(
  fileURLToPath(import.meta.resolve('@fontsource-variable/geist/package.json')),
);

rmSync(FONTS, { recursive: true, force: true });
mkdirSync(FONTS, { recursive: true });

const css = ['wght.css', 'wght-italic.css']
  .map((file) => readFileSync(join(source, file), 'utf8'))
  .join('\n')
  .replaceAll("font-family: 'Geist Variable';", `font-family: '${FAMILY}';`)
  .replace(/url\(\.\/files\/([^)]+)\)/g, (_match, file: string) => {
    copyFileSync(join(source, 'files', file), join(FONTS, file));
    return `url(./fonts/${file})`;
  });

if (!css.includes(`font-family: '${FAMILY}'`) || !css.includes('url(./fonts/')) {
  throw new Error(
    'Unexpected @fontsource-variable/geist CSS format; update scripts/build-fonts.ts.',
  );
}

copyFileSync(join(source, 'LICENSE'), join(FONTS, 'OFL.txt'));
writeFileSync(
  join(OUT, 'fonts.css'),
  `/* Generated by scripts/build-fonts.ts. Do not edit. Geist: SIL Open Font License 1.1 (fonts/OFL.txt). */\n${css}`,
);
console.log(`✔ Fonts built: ${FAMILY} → src/styles/generated/fonts.css`);
